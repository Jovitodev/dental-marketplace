import { randomUUID } from "crypto";
import { officeRepository } from "../offices/office.repository";
import { userRepository } from "../users/user.repository";
import { JS_WEEKDAY_TO_WEEKDAY } from "../offices/office.model";
import { BookingProposal, ChatMessage, CreateBookingDTO } from "./booking.model";
import { bookingRepository } from "./booking.repository";

export class BookingValidationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "BookingValidationError";
  }
}

function parseDateOrThrow(date: string): Date {
  const parsed = new Date(`${date}T12:00:00`); // meio-dia evita bug de fuso na borda do dia
  if (isNaN(parsed.getTime())) throw new BookingValidationError("Data inválida.");
  return parsed;
}

function buildAutoMessage(booking: BookingProposal): ChatMessage {
  const text =
    `📋 Nova proposta de reserva recebida!\n` +
    `Dentista: ${booking.dentistName}\n` +
    `Consultório: ${booking.officeTitle}\n` +
    `Data: ${new Date(`${booking.date}T12:00:00`).toLocaleDateString("pt-BR")} (${booking.weekday}) — Turno: ${booking.shift}\n` +
    `Procedimento: ${booking.serviceName}\n` +
    `Valor tabelado: R$ ${booking.listedPrice.toFixed(2)} · Valor ofertado: R$ ${booking.offeredPrice.toFixed(2)}`;

  return {
    id: randomUUID(),
    senderId: booking.dentistId,
    senderName: booking.dentistName,
    text,
    createdAt: new Date().toISOString(),
    isAutoGenerated: true,
  };
}

export const bookingService = {
  async create(dentistId: string, data: CreateBookingDTO): Promise<BookingProposal> {
    if (!data.officeId) throw new BookingValidationError("officeId é obrigatório.");
    if (!data.date) throw new BookingValidationError("date é obrigatório.");
    if (!data.shift) throw new BookingValidationError("shift é obrigatório.");
    if (data.offeredPrice == null || data.offeredPrice <= 0) {
      throw new BookingValidationError("Informe um valor de oferta maior que zero.");
    }

    const office = await officeRepository.findById(data.officeId);
    if (!office) throw new BookingValidationError("Consultório não encontrado.");
    if (office.moderationStatus !== "APROVADO" || office.status !== "ATIVO") {
      throw new BookingValidationError("Este consultório não está disponível para reservas no momento.");
    }

    const dentist = await userRepository.findById(dentistId);
    if (!dentist) throw new BookingValidationError("Usuário não encontrado.");

    if (office.ownerId === dentistId) {
      throw new BookingValidationError("Você não pode enviar uma proposta para o seu próprio consultório.");
    }

    // Regra: dia da semana precisa estar entre os disponibilizados pelo proprietário.
    const parsedDate = parseDateOrThrow(data.date);
    const weekday = JS_WEEKDAY_TO_WEEKDAY[parsedDate.getDay()];
    if (office.availableWeekdays.length > 0 && !office.availableWeekdays.includes(weekday)) {
      throw new BookingValidationError(
        `Este consultório não está disponível em ${weekday}. Dias disponíveis: ${office.availableWeekdays.join(", ")}.`
      );
    }

    // Regra de conflito: o MESMO dentista não pode ter duas propostas
    // pendentes/aceitas na mesma data+turno, mesmo em clínicas diferentes.
    const conflict = await bookingRepository.findActiveConflict(dentistId, data.date, data.shift);
    if (conflict) {
      throw new BookingValidationError(
        `Você já tem uma proposta ${conflict.status === "ACEITO" ? "aceita" : "pendente"} para ${data.date} no turno da ${data.shift.toLowerCase()} (consultório "${conflict.officeTitle}"). Não é possível ter dois compromissos no mesmo turno.`
      );
    }

    // Determina o serviço/preço tabelado.
    let serviceName = "Turno padrão";
    let listedPrice = office.shiftPrices.find((sp) => sp.shift === data.shift)?.price ?? 0;
    let serviceId: string | undefined;

    if (data.serviceId) {
      const service = office.services.find((s) => s.id === data.serviceId);
      if (!service) throw new BookingValidationError("Procedimento não encontrado neste consultório.");
      serviceId = service.id;
      serviceName = service.name;
      listedPrice = service.price;
    }

    const now = new Date().toISOString();
    const booking: BookingProposal = {
      id: randomUUID(),
      officeId: office.id,
      officeTitle: office.title,
      officeImageUrl: office.imageUrl,
      ownerId: office.ownerId,
      dentistId: dentist.id,
      dentistName: dentist.name,
      dentistAvatarUrl: dentist.avatarUrl,
      date: data.date,
      weekday,
      shift: data.shift,
      serviceId,
      serviceName,
      listedPrice,
      offeredPrice: data.offeredPrice,
      status: "PENDENTE_APROVACAO",
      messages: [],
      createdAt: now,
      updatedAt: now,
    };

    booking.messages.push(buildAutoMessage(booking));

    return bookingRepository.create(booking);
  },

  async getById(id: string): Promise<BookingProposal> {
    const booking = await bookingRepository.findById(id);
    if (!booking) throw new BookingValidationError("Proposta não encontrada.");
    return booking;
  },

  async listReceived(ownerId: string, status?: string): Promise<BookingProposal[]> {
    return bookingRepository.findByOwner(ownerId, status);
  },

  async listSent(dentistId: string, status?: string): Promise<BookingProposal[]> {
    return bookingRepository.findByDentist(dentistId, status);
  },

  async accept(id: string, actingOwnerId: string): Promise<BookingProposal> {
    const booking = await this.getById(id);
    if (booking.ownerId !== actingOwnerId) {
      throw new BookingValidationError("Apenas o proprietário do consultório pode aceitar esta proposta.");
    }
    if (booking.status === "ACEITO") return booking;

    const updated = await bookingRepository.update(id, { status: "ACEITO" });
    return updated as BookingProposal;
  },

  async reject(id: string, actingOwnerId: string): Promise<BookingProposal> {
    const booking = await this.getById(id);
    if (booking.ownerId !== actingOwnerId) {
      throw new BookingValidationError("Apenas o proprietário do consultório pode recusar esta proposta.");
    }

    const updated = await bookingRepository.update(id, { status: "RECUSADO" });
    return updated as BookingProposal;
  },

  async addMessage(id: string, senderId: string, text: string): Promise<BookingProposal> {
    const booking = await this.getById(id);
    if (senderId !== booking.ownerId && senderId !== booking.dentistId) {
      throw new BookingValidationError("Você não participa desta negociação.");
    }
    if (!text?.trim()) throw new BookingValidationError("Mensagem vazia.");

    const sender = await userRepository.findById(senderId);
    const message: ChatMessage = {
      id: randomUUID(),
      senderId,
      senderName: sender?.name ?? "Usuário",
      text: text.trim(),
      createdAt: new Date().toISOString(),
    };

    const messages = [...booking.messages, message];
    // Uma mensagem manual durante a análise inicia formalmente a negociação.
    const nextStatus = booking.status === "PENDENTE_APROVACAO" ? "NEGOCIACAO" : booking.status;

    const updated = await bookingRepository.update(id, { messages, status: nextStatus });
    return updated as BookingProposal;
  },
};
