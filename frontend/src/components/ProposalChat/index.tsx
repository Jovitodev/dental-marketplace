import { FormEvent, useState } from "react";
import { bookingService } from "../../services/booking";
import { BookingProposal } from "../../types/booking";
import { useAuth } from "../../context/AuthContext";

interface ProposalChatProps {
  proposal: BookingProposal;
  onClose: () => void;
  onUpdated: (updated: BookingProposal) => void;
}

/**
 * Chat de negociação embutido em uma proposta específica.
 * Não é o módulo de chat geral da plataforma — é o histórico de mensagens
 * (incluindo a mensagem automática estruturada) de UMA proposta de reserva.
 */
export default function ProposalChat({ proposal, onClose, onUpdated }: ProposalChatProps) {
  const { user } = useAuth();
  const [text, setText] = useState("");
  const [sending, setSending] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function handleSend(e: FormEvent) {
    e.preventDefault();
    if (!text.trim()) return;

    try {
      setSending(true);
      setError(null);
      const updated = await bookingService.sendMessage(proposal.id, text.trim());
      onUpdated(updated);
      setText("");
    } catch (err: any) {
      setError(err?.response?.data?.message || "Erro ao enviar mensagem.");
    } finally {
      setSending(false);
    }
  }

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div className="modal-card chat-modal" onClick={(e) => e.stopPropagation()}>
        <div className="modal-header">
          <div>
            <strong>Negociação — {proposal.officeTitle}</strong>
            <p className="helper-text">
              {proposal.dentistName} · {new Date(`${proposal.date}T12:00:00`).toLocaleDateString("pt-BR")}
            </p>
          </div>
          <button className="modal-close" onClick={onClose} aria-label="Fechar">
            ✕
          </button>
        </div>

        <div className="chat-messages">
          {proposal.messages.map((msg) => (
            <div
              key={msg.id}
              className={`chat-message ${msg.senderId === user?.id ? "own" : ""} ${
                msg.isAutoGenerated ? "auto" : ""
              }`}
            >
              {!msg.isAutoGenerated && <strong className="chat-message-author">{msg.senderName}</strong>}
              <p style={{ whiteSpace: "pre-line" }}>{msg.text}</p>
              <span className="chat-message-time">
                {new Date(msg.createdAt).toLocaleString("pt-BR", { day: "2-digit", month: "2-digit", hour: "2-digit", minute: "2-digit" })}
              </span>
            </div>
          ))}
        </div>

        {error && <p className="error-text" style={{ padding: "0 16px" }}>{error}</p>}

        <form className="chat-input-row" onSubmit={handleSend}>
          <input
            value={text}
            onChange={(e) => setText(e.target.value)}
            placeholder="Escreva uma mensagem..."
          />
          <button type="submit" className="btn-primary" disabled={sending || !text.trim()}>
            Enviar
          </button>
        </form>
      </div>
    </div>
  );
}
