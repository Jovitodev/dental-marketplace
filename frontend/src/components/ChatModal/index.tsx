import { FormEvent, useState } from "react";
import { toast } from "sonner";
import { ChatMessage } from "../../types/chat";
import { useAuth } from "../../context/AuthContext";

interface ChatModalProps {
  title: string;
  subtitle?: string;
  messages: ChatMessage[];
  onClose: () => void;
  onSend: (text: string) => Promise<void>;
}

/**
 * Modal de chat genérico e sem estado de dados próprio: recebe as mensagens
 * já carregadas e delega o envio para `onSend`. Usado tanto pelo chat
 * embutido em uma proposta de reserva (ver ProposalChat) quanto pelas
 * conversas diretas iniciadas em "Enviar mensagem ao anfitrião".
 *
 * Os toasts de sucesso/erro ficam centralizados aqui (em vez de duplicados
 * em cada wrapper) já que este é o único ponto por onde toda mensagem passa.
 */
export default function ChatModal({ title, subtitle, messages, onClose, onSend }: ChatModalProps) {
  const { user } = useAuth();
  const [text, setText] = useState("");
  const [sending, setSending] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function handleSend(e: FormEvent) {
    e.preventDefault();
    if (!text.trim()) return;

    try {
      setSending(true);
      setError(null);
      await onSend(text.trim());
      setText("");
      toast.success("Mensagem enviada com sucesso!");
    } catch (err: any) {
      const message = err?.response?.data?.message || "Erro ao enviar mensagem.";
      setError(message);
      toast.error(message);
    } finally {
      setSending(false);
    }
  }

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div className="modal-card chat-modal" onClick={(e) => e.stopPropagation()}>
        <div className="modal-header">
          <div>
            <strong>{title}</strong>
            {subtitle && <p className="helper-text">{subtitle}</p>}
          </div>
          <button className="modal-close" onClick={onClose} aria-label="Fechar">
            ✕
          </button>
        </div>

        <div className="chat-messages">
          {messages.length === 0 && <p className="helper-text">Nenhuma mensagem ainda. Diga olá!</p>}
          {messages.map((msg) => (
            <div
              key={msg.id}
              className={`chat-message ${msg.senderId === user?.id ? "own" : ""} ${
                msg.isAutoGenerated ? "auto" : ""
              }`}
            >
              {!msg.isAutoGenerated && <strong className="chat-message-author">{msg.senderName}</strong>}
              <p style={{ whiteSpace: "pre-line" }}>{msg.text}</p>
              <span className="chat-message-time">
                {new Date(msg.createdAt).toLocaleString("pt-BR", {
                  day: "2-digit",
                  month: "2-digit",
                  hour: "2-digit",
                  minute: "2-digit",
                })}
              </span>
            </div>
          ))}
        </div>

        {error && (
          <p className="error-text" style={{ padding: "0 16px" }}>
            {error}
          </p>
        )}

        <form className="chat-input-row" onSubmit={handleSend}>
          <input value={text} onChange={(e) => setText(e.target.value)} placeholder="Escreva uma mensagem..." />
          <button type="submit" className="btn-primary" disabled={sending || !text.trim()}>
            Enviar
          </button>
        </form>
      </div>
    </div>
  );
}
